export async function POST(request: NextRequest) {
  try {
    const user = await getCurrentUser(request)
    if (!user) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 })
    }

    if (!["uk", "super_admin"].includes(user.role)) {
      return NextResponse.json({ error: "Forbidden" }, { status: 403 })
    }

    if (!process.env.DATABASE_URL) {
      return NextResponse.json({ error: "Database not configured" }, { status: 500 })
    }

    const sql = neon(process.env.DATABASE_URL)

    // Check if already seeded
    const existing = await sql`
      SELECT COUNT(*)::int as count FROM "KnowledgeArticle"
      WHERE title LIKE 'Руководство%' OR title LIKE 'Как пользоваться%' OR title LIKE 'Уведомления%' OR title LIKE 'Как работать%'
    `
    if (existing[0].count > 5) {
      return NextResponse.json({ message: "Обучающие статьи уже созданы", count: existing[0].count })
    }

    const articles = getTrainingArticles()
    let created = 0

    for (const article of articles) {
      const id = `KB-SEED-${Date.now()}-${Math.random().toString(36).substr(2, 6)}`
      await sql`
        INSERT INTO "KnowledgeArticle" (id, title, category, content, author, "authorId", type, tags, views, helpful, "videoUrl", "targetRole", "createdAt", "updatedAt")
        VALUES (${id}, ${article.title}, ${article.category}, ${article.content}, ${user.name}, ${user.id}, ${article.type}, ${["обучение", "руководство"]}, 0, 0, ${null}, ${article.targetRole || null}, NOW(), NOW())
      `
      created++
    }

    return NextResponse.json({ success: true, created, message: `Создано ${created} обучающих статей` })
  } catch (error: any) {
    console.error("[v0] Knowledge seed error:", error)
    return NextResponse.json({ error: "Internal server error" }, { status: 500 })
  }
}
